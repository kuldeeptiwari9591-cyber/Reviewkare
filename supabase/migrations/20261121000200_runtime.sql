-- Compatibility schema for the existing application. The normalized foundation
-- remains reserved until workspaces and existing identifiers can be migrated.
CREATE SCHEMA reviewkare_runtime;
REVOKE ALL ON SCHEMA reviewkare_runtime FROM PUBLIC, anon, authenticated, service_role;
SET search_path TO reviewkare_runtime, pg_catalog;
CREATE TABLE tenants(id TEXT PRIMARY KEY, document TEXT NOT NULL, version BIGINT NOT NULL DEFAULT 1);

CREATE TABLE users(email TEXT PRIMARY KEY, tenant_id TEXT NOT NULL UNIQUE REFERENCES tenants(id) ON DELETE CASCADE, hash TEXT NOT NULL, salt TEXT NOT NULL, verified BIGINT NOT NULL DEFAULT 0);

CREATE TABLE sessions(hash TEXT PRIMARY KEY, email TEXT NOT NULL REFERENCES users(email) ON DELETE CASCADE, expires BIGINT NOT NULL);

CREATE TABLE capabilities(hash TEXT PRIMARY KEY, kind TEXT NOT NULL, email TEXT, tenant_id TEXT REFERENCES tenants(id) ON DELETE CASCADE, review_id TEXT, draft_hash TEXT, expires BIGINT NOT NULL, used BIGINT NOT NULL DEFAULT 0);

CREATE TABLE orders(id TEXT PRIMARY KEY, tenant_id TEXT NOT NULL, plan_id TEXT NOT NULL, cycle TEXT NOT NULL, amount BIGINT NOT NULL, currency TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'created', expires BIGINT NOT NULL, payment_id TEXT UNIQUE);

CREATE TABLE requests(id TEXT PRIMARY KEY, kind TEXT NOT NULL, tenant_id TEXT, document TEXT NOT NULL, created BIGINT NOT NULL);

CREATE TABLE audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id TEXT, action TEXT NOT NULL, created BIGINT NOT NULL);

CREATE TABLE public_profiles(tenant_id TEXT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE, document TEXT NOT NULL);

CREATE TABLE qr_codes(code TEXT PRIMARY KEY, tenant_id TEXT NOT NULL UNIQUE REFERENCES tenants(id) ON DELETE CASCADE, scans BIGINT NOT NULL DEFAULT 0, drafts BIGINT NOT NULL DEFAULT 0, usage_month TEXT NOT NULL DEFAULT '', monthly_drafts BIGINT NOT NULL DEFAULT 0);

CREATE TABLE reviews (
  id TEXT NOT NULL,
  tenant_id TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  location_id TEXT,
  reviewer_name TEXT NOT NULL,
  rating BIGINT NOT NULL CHECK(rating BETWEEN 1 AND 5),
  body TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'manual',
  status TEXT NOT NULL DEFAULT 'draft',
  draft_text TEXT,
  final_text TEXT,
  model TEXT,
  validator_passed BIGINT NOT NULL DEFAULT 0,
  is_auto_posted BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL, google_review_id TEXT, google_reply_state TEXT, published_at BIGINT,
  PRIMARY KEY (tenant_id, id)
);

CREATE TABLE review_candidates (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  review_id TEXT NOT NULL,
  model TEXT NOT NULL,
  style TEXT NOT NULL,
  draft_text TEXT NOT NULL,
  prompt_version TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  batch TEXT NOT NULL,
  score BIGINT NOT NULL DEFAULT 0,
  latency_ms BIGINT NOT NULL DEFAULT 0,
  prompt_tokens BIGINT NOT NULL DEFAULT 0,
  completion_tokens BIGINT NOT NULL DEFAULT 0,
  cost_micros BIGINT NOT NULL DEFAULT 0,
  selected_at BIGINT,
  created_at BIGINT NOT NULL,
  FOREIGN KEY (tenant_id, review_id) REFERENCES reviews(tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE ai_usage (
  tenant_id TEXT NOT NULL,
  month TEXT NOT NULL,
  generations BIGINT NOT NULL DEFAULT 0,
  candidates BIGINT NOT NULL DEFAULT 0,
  failures BIGINT NOT NULL DEFAULT 0,
  cost_micros BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (tenant_id, month)
);

CREATE TABLE google_connections (
  tenant_id TEXT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  google_email TEXT,
  account_name TEXT,
  location_name TEXT,
  location_title TEXT,
  scopes TEXT NOT NULL DEFAULT '',
  refresh_token TEXT NOT NULL,
  access_token TEXT,
  access_expires BIGINT NOT NULL DEFAULT 0,
  connected_at BIGINT NOT NULL,
  last_sync BIGINT,
  last_error TEXT
);

CREATE INDEX session_expiry ON sessions(expires);

CREATE INDEX reviews_tenant_created ON reviews(tenant_id, created_at DESC);

CREATE INDEX reviews_tenant_status ON reviews(tenant_id, status, created_at DESC);

CREATE INDEX review_candidates_review ON review_candidates(tenant_id, review_id, created_at DESC);

CREATE INDEX review_candidates_hash ON review_candidates(tenant_id, review_id, input_hash, created_at DESC);

CREATE UNIQUE INDEX reviews_google_id ON reviews(tenant_id, google_review_id);

CREATE INDEX reviews_source ON reviews(tenant_id, source, created_at DESC);
