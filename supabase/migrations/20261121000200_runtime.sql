ALTER TABLE users ALTER COLUMN hash DROP NOT NULL, ALTER COLUMN salt DROP NOT NULL;
CREATE TABLE rate_limits (
  bucket text PRIMARY KEY,
  window_end bigint NOT NULL,
  count integer NOT NULL CHECK (count > 0)
);
CREATE FUNCTION sync_public_profile() RETURNS trigger LANGUAGE plpgsql
SET search_path = reviewkare_runtime, pg_catalog AS $body$
BEGIN
  INSERT INTO public_profiles(tenant_id, document)
  VALUES (NEW.id, jsonb_build_object('id', NEW.id,
    'location', NEW.document::jsonb->'location', 'plan', NEW.document::jsonb->'plan',
    'qr', NEW.document::jsonb->'qr', 'guest', NEW.document::jsonb->'guest')::text)
  ON CONFLICT (tenant_id) DO UPDATE SET document = excluded.document;
  IF TG_OP = 'INSERT' THEN
    INSERT INTO qr_codes(code, tenant_id) VALUES (NEW.document::jsonb->'qr'->>'code', NEW.id);
  END IF;
  RETURN NEW;
END;
$body$;
CREATE TRIGGER tenant_public_sync AFTER INSERT OR UPDATE OF document ON tenants
FOR EACH ROW EXECUTE FUNCTION sync_public_profile();
DO $body$
DECLARE relation record;
BEGIN
  FOR relation IN SELECT tablename FROM pg_tables WHERE schemaname = 'reviewkare_runtime'
  LOOP
    EXECUTE format('ALTER TABLE reviewkare_runtime.%I ENABLE ROW LEVEL SECURITY', relation.tablename);
  END LOOP;
END;
$body$;
REVOKE ALL ON ALL TABLES IN SCHEMA reviewkare_runtime FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA reviewkare_runtime FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION sync_public_profile() FROM PUBLIC, anon, authenticated, service_role;

-- Supabase Auth account removal and app data removal commit together.
CREATE FUNCTION remove_auth_workspace() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = reviewkare_runtime, pg_catalog AS $body$
DECLARE workspace text;
BEGIN
  SELECT tenant_id INTO workspace FROM users WHERE auth_user_id = OLD.id;
  IF workspace IS NOT NULL THEN
    UPDATE orders SET tenant_id = 'deleted_' || gen_random_uuid()::text WHERE tenant_id = workspace;
    DELETE FROM requests WHERE tenant_id = workspace;
    DELETE FROM ai_usage WHERE tenant_id = workspace;
    DELETE FROM audit WHERE tenant_id = workspace;
    DELETE FROM tenants WHERE id = workspace;
  END IF;
  RETURN OLD;
END;
$body$;
REVOKE ALL ON FUNCTION remove_auth_workspace() FROM PUBLIC, anon, authenticated, service_role;
CREATE TRIGGER reviewkare_remove_workspace BEFORE DELETE ON auth.users
FOR EACH ROW EXECUTE FUNCTION reviewkare_runtime.remove_auth_workspace();
RESET search_path;
